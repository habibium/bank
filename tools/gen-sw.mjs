#!/usr/bin/env node
// Regenerates sw.js from tools/sw.template.js with a content-hashed precache manifest.
// Must be re-run and committed whenever a deployable file changes; CI enforces this.
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATE = join(ROOT, "tools", "sw.template.js");
const OUTPUT = join(ROOT, "sw.js");

const SKIP_DIRS = new Set([".git", ".github", "node_modules", "tools"]);
// Served by Pages but pointless to precache; sw.js must never precache itself.
const SKIP_FILES = new Set(["sw.js", "CNAME", "README.md", ".nojekyll", ".gitignore"]);

async function collect(dir = ROOT, found = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) await collect(path, found);
    } else if (entry.isFile() && !SKIP_FILES.has(relative(ROOT, path))) {
      found.push(path);
    }
  }
  return found;
}

function hash(input) {
  return createHash("sha256").update(input).digest("hex").slice(0, 16);
}

const files = (await collect()).sort();
const entries = new Map();

for (const path of files) {
  const url = `/${relative(ROOT, path).split(/[\\/]/).map(encodeURIComponent).join("/")}`;
  entries.set(url, hash(await readFile(path)));
}

const shell = entries.get("/index.html");
if (!shell) throw new Error("index.html is missing; refusing to emit a worker without an app shell");
entries.set("/", shell);

const sorted = [...entries].sort(([a], [b]) => (a < b ? -1 : 1));
const version = hash(sorted.map(([url, digest]) => `${url}\t${digest}`).join("\n"));
const manifest = JSON.stringify(Object.fromEntries(sorted), null, 2);

const template = await readFile(TEMPLATE, "utf8");
const generated = template
  .replace("// Template for sw.js. Edit this file, then run `node tools/gen-sw.mjs`.",
    "// Generated by tools/gen-sw.mjs. Do not edit; edit tools/sw.template.js and regenerate.")
  .replace("__PRECACHE_VERSION__", version)
  .replace("__PRECACHE_ENTRIES__", manifest);

if (generated.includes("__PRECACHE_")) throw new Error("template placeholders were not all replaced");

await writeFile(OUTPUT, generated);
console.log(`sw.js: ${sorted.length} urls, version ${version}`);
